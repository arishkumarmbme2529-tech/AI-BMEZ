"""
PDF Report Generator using ReportLab.
Generates professional validation reports for AICTE applications.
"""
import os
from datetime import datetime
from typing import Optional


def generate_application_report(application, file_path: str, db) -> None:
    """Generate a professional PDF validation report for an application."""
    try:
        from reportlab.lib import colors
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.units import cm, mm
        from reportlab.platypus import (
            SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle,
            HRFlowable, PageBreak
        )
        from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_RIGHT

        # Colors
        NAVY = colors.HexColor("#1e3a5f")
        CYAN = colors.HexColor("#06b6d4")
        LIGHT_GRAY = colors.HexColor("#f8fafc")
        MID_GRAY = colors.HexColor("#64748b")
        GREEN = colors.HexColor("#22c55e")
        RED = colors.HexColor("#ef4444")
        ORANGE = colors.HexColor("#f59e0b")

        # Document setup
        doc = SimpleDocTemplate(
            file_path,
            pagesize=A4,
            rightMargin=2*cm, leftMargin=2*cm,
            topMargin=2*cm, bottomMargin=2*cm,
        )

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            "CustomTitle", parent=styles["Title"],
            fontSize=18, textColor=NAVY, spaceAfter=6, alignment=TA_CENTER,
            fontName="Helvetica-Bold"
        )
        subtitle_style = ParagraphStyle(
            "Subtitle", parent=styles["Normal"],
            fontSize=11, textColor=MID_GRAY, spaceAfter=4, alignment=TA_CENTER,
        )
        heading_style = ParagraphStyle(
            "Heading", parent=styles["Heading2"],
            fontSize=13, textColor=NAVY, spaceBefore=12, spaceAfter=6,
            fontName="Helvetica-Bold"
        )
        normal_style = ParagraphStyle(
            "Body", parent=styles["Normal"],
            fontSize=10, textColor=colors.black, spaceAfter=4,
        )
        small_style = ParagraphStyle(
            "Small", parent=styles["Normal"],
            fontSize=8, textColor=MID_GRAY,
        )

        story = []

        # ── Cover Page ──────────────────────────────────────────────
        story.append(Spacer(1, 1*cm))
        story.append(HRFlowable(width="100%", thickness=3, color=NAVY))
        story.append(Spacer(1, 0.3*cm))
        story.append(Paragraph("AICTE SMART DOCUMENT MANAGEMENT PLATFORM", title_style))
        story.append(Paragraph("All India Council for Technical Education", subtitle_style))
        story.append(Paragraph("Regulation Bureau — Application Validation Report", subtitle_style))
        story.append(Spacer(1, 0.3*cm))
        story.append(HRFlowable(width="100%", thickness=1, color=CYAN))
        story.append(Spacer(1, 0.5*cm))

        # Report metadata table
        inst = application.institution
        now = datetime.utcnow()
        cover_data = [
            ["Report Type:", "Application Validation Report"],
            ["Application ID:", application.application_id],
            ["Institution:", inst.name if inst else "N/A"],
            ["AICTE ID:", inst.aicte_id if inst else "N/A"],
            ["Category:", application.category.name if application.category else "N/A"],
            ["Status:", application.status],
            ["Generated On:", now.strftime("%d %B %Y, %H:%M UTC")],
        ]
        cover_table = Table(cover_data, colWidths=[4.5*cm, 12*cm])
        cover_table.setStyle(TableStyle([
            ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 10),
            ("TEXTCOLOR", (0, 0), (0, -1), NAVY),
            ("ROWBACKGROUNDS", (0, 0), (-1, -1), [LIGHT_GRAY, colors.white]),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ]))
        story.append(cover_table)
        story.append(Spacer(1, 0.5*cm))

        disclaimer = (
            "<b>IMPORTANT NOTICE:</b> This report is generated by the AICTE Smart Document "
            "Management Platform for demonstration and review purposes. AI-generated findings "
            "are preliminary indicators only. All compliance results are based on sample rules "
            "and do not constitute official regulatory determinations. This system is a "
            "demonstration for SIH 2026 Problem Statement 26261."
        )
        story.append(Paragraph(disclaimer, ParagraphStyle(
            "Disclaimer", parent=styles["Normal"],
            fontSize=8, textColor=MID_GRAY,
            borderColor=ORANGE, borderWidth=1, borderPadding=8,
            backColor=colors.HexColor("#fffbeb"),
        )))

        story.append(PageBreak())

        # ── Institution Details ─────────────────────────────────────
        story.append(Paragraph("1. Institution Details", heading_style))
        story.append(HRFlowable(width="100%", thickness=1, color=CYAN))
        story.append(Spacer(1, 0.3*cm))
        if inst:
            inst_data = [
                ["Institution Name", inst.name],
                ["AICTE Institution ID", inst.aicte_id],
                ["Institution Type", inst.institution_type or "N/A"],
                ["State", inst.state or "N/A"],
                ["District", inst.district or "N/A"],
                ["City / Pincode", f"{inst.city or 'N/A'} — {inst.pincode or 'N/A'}"],
                ["Contact Person", inst.contact_person or "N/A"],
                ["Email", inst.email or "N/A"],
                ["Phone", inst.phone or "N/A"],
                ["Establishment Year", str(inst.establishment_year) if inst.establishment_year else "N/A"],
                ["Status", inst.status],
            ]
            inst_table = Table(inst_data, colWidths=[5*cm, 11.5*cm])
            inst_table.setStyle(TableStyle([
                ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
                ("ROWBACKGROUNDS", (0, 0), (-1, -1), [LIGHT_GRAY, colors.white]),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ("TOPPADDING", (0, 0), (-1, -1), 5),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ]))
            story.append(inst_table)

        # ── Document Checklist ──────────────────────────────────────
        story.append(Spacer(1, 0.5*cm))
        story.append(Paragraph("2. Uploaded Documents", heading_style))
        story.append(HRFlowable(width="100%", thickness=1, color=CYAN))
        story.append(Spacer(1, 0.3*cm))

        docs = [d for d in application.documents if d.is_active]
        if docs:
            doc_data = [["#", "Document Name", "Type", "Status", "Upload Date"]]
            for i, d in enumerate(docs, 1):
                doc_data.append([
                    str(i),
                    d.original_filename[:40],
                    d.document_type.name if d.document_type else "N/A",
                    d.status,
                    d.upload_date.strftime("%d/%m/%Y") if d.upload_date else "N/A",
                ])
            doc_table = Table(doc_data, colWidths=[1*cm, 6*cm, 4*cm, 3*cm, 2.5*cm])
            doc_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), NAVY),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 8),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [LIGHT_GRAY, colors.white]),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ("ALIGN", (0, 0), (0, -1), "CENTER"),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]))
            story.append(doc_table)
        else:
            story.append(Paragraph("No documents uploaded for this application.", normal_style))

        # ── Compliance Results ──────────────────────────────────────
        from app.db.models import ComplianceResult, AuthenticationResult, Alert as AlertModel
        story.append(Spacer(1, 0.5*cm))
        story.append(Paragraph("3. Compliance Check Results [SAMPLE RULES]", heading_style))
        story.append(HRFlowable(width="100%", thickness=1, color=CYAN))
        story.append(Spacer(1, 0.3*cm))

        comp_results = db.query(ComplianceResult).filter(
            ComplianceResult.application_id == application.id
        ).all()
        if comp_results:
            comp_data = [["Rule ID", "Rule Name", "Severity", "Status"]]
            for r in comp_results:
                status_color = GREEN if r.status == "COMPLIANT" else (
                    RED if r.status == "NON_COMPLIANT" else ORANGE
                )
                comp_data.append([
                    r.rule.rule_id if r.rule else "N/A",
                    (r.rule.name if r.rule else "N/A")[:40],
                    r.rule.severity if r.rule else "N/A",
                    r.status,
                ])
            comp_table = Table(comp_data, colWidths=[2.5*cm, 8*cm, 3*cm, 3*cm])
            comp_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), NAVY),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 8),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [LIGHT_GRAY, colors.white]),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]))
            story.append(comp_table)
        else:
            story.append(Paragraph("No compliance check has been run for this application yet.", normal_style))

        # ── Authentication Results ──────────────────────────────────
        story.append(Spacer(1, 0.5*cm))
        story.append(Paragraph("4. Document Authentication Results [AI PRELIMINARY]", heading_style))
        story.append(HRFlowable(width="100%", thickness=1, color=CYAN))
        story.append(Spacer(1, 0.3*cm))

        auth_results = db.query(AuthenticationResult).filter(
            AuthenticationResult.application_id == application.id
        ).all()
        if auth_results:
            auth_data = [["Document ID", "Status", "Similarity Score", "Findings"]]
            for r in auth_results:
                auth_data.append([
                    str(r.document_id),
                    r.status,
                    f"{r.similarity_score:.1%}" if r.similarity_score else "N/A",
                    str(len(r.anomaly_findings or [])) + " finding(s)",
                ])
            auth_table = Table(auth_data, colWidths=[3*cm, 5*cm, 4*cm, 4.5*cm])
            auth_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), NAVY),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                ("FONTSIZE", (0, 0), (-1, -1), 8),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [LIGHT_GRAY, colors.white]),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]))
            story.append(auth_table)
        else:
            story.append(Paragraph("No authentication analysis has been run.", normal_style))

        # ── Alerts & Recommendations ────────────────────────────────
        story.append(Spacer(1, 0.5*cm))
        story.append(Paragraph("5. Open Alerts & Recommendations", heading_style))
        story.append(HRFlowable(width="100%", thickness=1, color=CYAN))
        story.append(Spacer(1, 0.3*cm))

        open_alerts = db.query(AlertModel).filter(
            AlertModel.application_id == application.id,
            AlertModel.is_resolved == False,
        ).all()
        if open_alerts:
            for a in open_alerts:
                story.append(Paragraph(
                    f"<b>[{a.severity}]</b> {a.title}: {a.message}",
                    normal_style
                ))
        else:
            story.append(Paragraph("No open alerts for this application.", normal_style))

        # ── Footer / Signature ──────────────────────────────────────
        story.append(Spacer(1, 1*cm))
        story.append(HRFlowable(width="100%", thickness=1, color=NAVY))
        story.append(Spacer(1, 0.3*cm))
        story.append(Paragraph(
            f"Report generated by AICTE Smart Document Management Platform on "
            f"{now.strftime('%d %B %Y at %H:%M UTC')} | SIH 2026 — Problem Statement 26261 | "
            f"Demonstration data — Not official AICTE output",
            small_style,
        ))

        doc.build(story)

    except ImportError as e:
        # ReportLab not available — write a plain text report
        with open(file_path.replace(".pdf", ".txt"), "w") as f:
            f.write(f"AICTE Smart Platform — Validation Report\n")
            f.write(f"Application: {application.application_id}\n")
            f.write(f"Institution: {application.institution.name if application.institution else 'N/A'}\n")
            f.write(f"Generated: {datetime.utcnow().isoformat()}\n")
            f.write(f"Note: ReportLab not installed — PDF generation unavailable.\n")
        # Create empty PDF placeholder
        with open(file_path, "wb") as f:
            f.write(b"%PDF-1.0\n1 0 obj<</Type/Catalog/Pages 2 0 R>>endobj 2 0 obj<</Type/Pages/Kids[3 0 R]/Count 1>>endobj 3 0 obj<</Type/Page/MediaBox[0 0 612 792]>>endobj\nxref\n0 4\n0000000000 65535 f\n0000000009 00000 n\n0000000058 00000 n\n0000000115 00000 n\ntrailer<</Size 4/Root 1 0 R>>\nstartxref\n190\n%%EOF")

